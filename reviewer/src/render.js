// render.js
// Guardrails: G18 (one marker comment, idempotent upsert), G19 (footer with AI assisted advisory),
//             G35 (wrapper-generated header and footer; model text cannot alter them)
// Builds the complete PR comment string per CONTRACTS section 5.
// No runtime dependencies.

const MARKER_PREFIX = '<!-- bob-pr-review:v1 ';
const ADVISORY_HEADER = '> **AI Assisted review (advisory).** Generated by IBM Bob. It does not approve or block this pull\n> request. A human reviewer makes the final evaluation.';

// buildMarker generates the hidden marker line with cumulative metadata. (G18)
function buildMarker(headSha, runs, costTotal) {
  const meta = JSON.stringify({ head: headSha, runs, cost_total: costTotal });
  return `${MARKER_PREFIX}${meta} -->`;
}

// parseMarker extracts the metadata from an existing marker comment, or returns null. (G18)
export function parseMarker(commentBody) {
  if (!commentBody || typeof commentBody !== 'string') return null;
  const firstLine = commentBody.split('\n')[0].trim();
  if (!firstLine.startsWith(MARKER_PREFIX)) return null;
  const jsonStr = firstLine.slice(MARKER_PREFIX.length).replace(/\s*-->$/, '');
  try {
    return JSON.parse(jsonStr);
  } catch {
    return null;
  }
}

// renderFinding formats one finding. (G35 - text is already sanitised before this)
function renderFinding(f) {
  const severityLabel = `[${(f.severity ?? 'info').toUpperCase()}]`;
  const ruleLabel = f.rule_id ? ` Rule \`${f.rule_id}\`` : '';
  const locLabel = `\`${f.file}:${f.line}\``;
  const lines = [`- **${severityLabel} ${f.title ?? '(no title)'}** ${locLabel} (confidence: ${f.confidence ?? 'unknown'})${ruleLabel}`];
  if (f.explanation) lines.push(`  ${f.explanation}`);
  if (f.evidence)    lines.push(`  Evidence: ${f.evidence}`);
  if (f.proposed_fix) {
    lines.push('  Suggested fix (not applied):');
    lines.push('  ```diff');
    for (const l of f.proposed_fix.split('\n')) lines.push('  ' + l);
    lines.push('  ```');
  }
  return lines.join('\n');
}

function renderSection(title, findings) {
  if (!findings || findings.length === 0) return null;
  const lines = [`#### ${title} (${findings.length})`];
  for (const f of findings) lines.push(renderFinding(f));
  return lines.join('\n');
}

// renderComment builds the full comment string per CONTRACTS section 5. (G18, G35)
export function renderComment({
  headSha, runs, costRecord, output, rulesStatus, bobVersion, runId, priorCostBobcoins = 0,
}) {
  // Cumulative PR cost: spend of earlier runs (from the previous marker) plus this run. (G14, G37)
  const costTotal = {
    bobcoins: +(priorCostBobcoins + (costRecord?.bob_usage?.total ?? 0)).toFixed(6),
  };
  const marker = buildMarker(headSha, runs, costTotal);

  const findings = output?.findings ?? [];
  const attention = output?.needs_human_attention ?? [];
  const summary = output?.summary ?? '';

  const secFindings    = findings.filter(f => f.category === 'security');
  const stdFindings    = findings.filter(f => f.category === 'standards');
  const teamFindings   = findings.filter(f => f.category === 'team_rule');
  const otherFindings  = findings.filter(f => f.category === 'other');

  const parts = [marker, '', ADVISORY_HEADER];

  // Summary section.
  if (summary) {
    parts.push('', '### Summary', summary);
  }

  // Findings sections.
  const hasFindings = findings.length > 0;
  if (hasFindings) {
    parts.push('', '### Findings');
    const secSection   = renderSection('Security',    secFindings);
    const stdSection   = renderSection('Standards',   stdFindings);
    const teamSection  = renderSection('Team rules',  teamFindings);
    const otherSection = renderSection('Other',       otherFindings);
    if (secSection)   parts.push(secSection);
    if (stdSection)   parts.push(stdSection);
    if (teamSection)  parts.push(teamSection);
    if (otherSection) parts.push(otherSection);
  } else {
    parts.push('', '### Findings', '_No findings in this review._');
  }

  // Needs human attention section.
  if (attention.length > 0) {
    parts.push('', '### Needs human attention');
    for (const item of attention) {
      parts.push(`- ${item.title}: ${item.reason}`);
    }
  }

  // Footer line. (G19, G35)
  const shortSha = typeof headSha === 'string' ? headSha.slice(0, 7) : 'unknown';
  const versionStr = bobVersion ? `Bob Shell ${bobVersion}` : 'Bob Shell (version unknown)';
  const runIdStr = runId ?? 'n/a';
  const stdStatus  = rulesStatus?.standards  ? 'yes' : 'no';
  const teamStatus = rulesStatus?.teamRules  ? 'yes' : 'no';
  const costBobcoins = costRecord?.bob_usage?.total;
  const costThisRun  = costBobcoins != null ? `${costBobcoins.toFixed(4)} Bobcoins (reported)` : 'not reported';
  const prTotal      = `${costTotal.bobcoins.toFixed(4)} Bobcoins`;

  parts.push('');
  parts.push('---');
  parts.push(`Reviewed commit \`${shortSha}\` | ${versionStr} | run ${runIdStr} | rules: standards ${stdStatus}, team ${teamStatus}`);
  parts.push(`Cost this run: ${costThisRun}, PR total: ${prTotal} over ${runs} run(s). AI Assisted, advisory only.`);

  return parts.join('\n');
}

// renderUnavailableComment builds a short "review unavailable" note. (G18, G35)
export function renderUnavailableComment({ headSha, runs, costRecord, outcome, detail, priorCostBobcoins = 0 }) {
  // Keep the cumulative spend even when this run produced no review. (G14, G37)
  const costTotal = { bobcoins: +(priorCostBobcoins + (costRecord?.bob_usage?.total ?? 0)).toFixed(6) };
  const marker = buildMarker(headSha, runs, costTotal);
  const shortSha = typeof headSha === 'string' ? headSha.slice(0, 7) : 'unknown';
  const parts = [
    marker,
    '',
    ADVISORY_HEADER,
    '',
    `### Review unavailable`,
    `The automated review could not complete for this commit (\`${shortSha}\`). Outcome: \`${outcome}\`.`,
  ];
  if (detail) parts.push(`Details: ${detail}`);
  parts.push('', '_A human reviewer should check this pull request manually._');
  return parts.join('\n');
}

export default renderComment;
